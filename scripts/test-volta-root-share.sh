#!/bin/bash
# Test harness for scripts/volta-root-share.sh. Runs the installer against a
# throwaway tree via a fake `sudo` and the VOLTA_SHARE_* path overrides — it
# never touches /usr/local, /etc or /root on the machine it runs on.
#
# Usage: bash scripts/test-volta-root-share.sh
# Exit:  0 all green, 1 something failed.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$REPO/scripts/volta-root-share.sh"
T="$(mktemp -d /tmp/volta-root-share-test-XXXXXX)"
trap 'rm -rf "$T"' EXIT

pass=0
fail=0
ck() { # ck <label> <command...>
  local label="$1"
  shift
  if "$@" >/dev/null 2>&1; then
    printf 'ok   %s\n' "$label"
    pass=$((pass + 1))
  else
    printf 'FAIL %s\n' "$label"
    fail=$((fail + 1))
  fi
}
lacks() { ! "$@"; }   # lacks <cmd...> = "the grep must NOT match"

# --- fake root -------------------------------------------------------------
# $FAKE mirrors the filesystem paths the installer writes. The sudo shim rewrites
# absolute paths under those roots so `sudo tee /etc/...` lands in the sandbox.
FAKE="$T/fakeroot"
mkdir -p "$T/bin" "$FAKE/usr/local/lib/volta" "$FAKE/etc/profile.d" \
       "$FAKE/root" "$FAKE/usr/local/bin"
cat >"$T/bin/sudo" <<EOF
#!/bin/bash
out=()
for a in "\$@"; do
  case "\$a" in
    /root/*|/etc/*|/usr/local/*) out+=("$FAKE\$a") ;;
    *) out+=("\$a") ;;
  esac
done
exec "\${out[@]}"
EOF
chmod +x "$T/bin/sudo"
export PATH="$T/bin:$PATH"

# --- fake user: a volta home with a pinned image and a shim farm alias -------
VHOME="$T/home/.volta"
mkdir -p "$VHOME/bin" "$VHOME/tools/image/node/26.12.0/bin"
printf '#!/bin/sh\necho shim\n' >"$VHOME/bin/node"
printf '#!/bin/sh\necho node\n' >"$VHOME/tools/image/node/26.12.0/bin/node"
chmod +x "$VHOME/bin/node" "$VHOME/tools/image/node/26.12.0/bin/node"
ln -s "$VHOME" "$FAKE/usr/local/lib/volta/home"
  # single quotes on purpose: these are literal file contents, not expansions
  # shellcheck disable=SC2016
printf '#!/bin/sh\n# Generated by dotfiles INSTALL.sh\nVH=%s\ncase x in *) exec "\$VH"/tools/image/node/26.12.0/bin/node pi.js "\$@\";; esac\n' \
  "$VHOME" >"$FAKE/usr/local/bin/pi"

SHARE_ENV=(
  "VOLTA_SHARE_DIR=$FAKE/usr/local/lib/volta"
  "VOLTA_SHARE_PROFILE_SH=$FAKE/etc/profile.d/volta.sh"
  "VOLTA_SHARE_ROOT_BASHRC=$FAKE/root/.bashrc"
  "VOLTA_SHARE_PI=$FAKE/usr/local/bin/pi"
  "VOLTA_SHARE_HOME=$VHOME"
)
share() { env "${SHARE_ENV[@]}" bash "$SCRIPT" "$@"; }

echo "== 1. fresh machine: nothing installed yet =="
: >"$FAKE/root/.bashrc"
rm -f "$FAKE/etc/profile.d/volta.sh" "$FAKE/usr/local/lib/volta/env"
share apply >"$T/apply1.log" 2>&1
ck "env file written"         test -s "$FAKE/usr/local/lib/volta/env"
ck "profile.d sources env"    grep -qE '^\[ -r .*volta/env \] && \. .*volta/env$' "$FAKE/etc/profile.d/volta.sh"
ck "profile.d has no PATH"    lacks grep -qE 'PATH=.*VOLTA_HOME/bin' "$FAKE/etc/profile.d/volta.sh"
ck "root bashrc hooked"       grep -q 'volta-root-share/v2' "$FAKE/root/.bashrc"
ck "check passes afterwards"  share check

echo "== 2. idempotent: re-apply does not duplicate the hook =="
share apply >"$T/apply2.log" 2>&1
# 2 = the open + close marker lines of exactly one block
ck "hook appears once" test "$(grep -c 'volta-root-share/v2' "$FAKE/root/.bashrc")" = 2

echo "== 3. heals a v1 machine (farm spelling exported inline) =="
cat >"$FAKE/root/.bashrc" <<'BASHRC'
# ~/.bashrc: executed by bash(1) for non-login shells.
case $- in *i*) ;; *) return;; esac
# volta shims (node/npm/pi shared from the installing user's setup)
export VOLTA_HOME=/usr/local/lib/volta/home
export PATH="$VOLTA_HOME/bin:$PATH"
BASHRC
  # single quotes on purpose: these are literal file contents, not expansions
  # shellcheck disable=SC2016
printf '# volta shims (node/npm/pi shared from the installing user%s setup)\nexport VOLTA_HOME=/usr/local/lib/volta/home\nexport PATH="$VOLTA_HOME/bin:$PATH"\n' "'" \
  >"$FAKE/usr/local/lib/volta/env"
cp "$FAKE/usr/local/lib/volta/env" "$FAKE/etc/profile.d/volta.sh"
share check >"$T/check3.log" 2>&1 || true
ck "check flags the v1 env file"   grep -q 'differs from this script' "$T/check3.log"
ck "check flags profile.d PATH"    grep -q 'shim dir on PATH'         "$T/check3.log"
ck "check flags farm VOLTA_HOME"   grep -q 'farm spelling'            "$T/check3.log"
share apply >"$T/apply3.log" 2>&1
ck "apply reports the strip"       grep -q 'stale copy'               "$T/apply3.log"
ck "backup kept"                   test -f "$FAKE/root/.bashrc.pre-volta-root-share.bak"
ck "v1 export gone from bashrc"    lacks grep -q 'VOLTA_HOME=/usr/local/lib/volta/home' "$FAKE/root/.bashrc"
ck "bashrc keeps its own body"     grep -q 'case \$- in' "$FAKE/root/.bashrc"
ck "converged"                     share check
ck "snippet canonicalizes VH"      grep -qE 'readlink -f .*volta/home' "$FAKE/usr/local/lib/volta/env"

echo "== 4. a shim-exec pi wrapper is reported =="
  # single quotes on purpose: these are literal file contents, not expansions
  # shellcheck disable=SC2016
printf '#!/bin/sh\nexport VOLTA_HOME=/usr/local/lib/volta/home\nexec "$VOLTA_HOME/bin/pi" "$@"\n' >"$FAKE/usr/local/bin/pi"
share check >"$T/check4.log" 2>&1 || true
ck "check flags the shim wrapper"  grep -q 'Volta shims' "$T/check4.log"
share apply >"$T/apply4.log" 2>&1
ck "apply removes it"              test ! -e "$FAKE/usr/local/bin/pi"
ck "apply backs it up"             test -f "$FAKE/usr/local/bin/pi.pre-volta-root-share"
ck "removal is reported"           grep -q 'shim-exec' "$T/apply4.log"
ck "converged after removal"       share check
printf '#!/bin/sh\n# Generated by dotfiles INSTALL.sh\nexec %s/tools/image/node/26.12.0/bin/node pi.js "$@"\n' \
  "$VHOME" >"$FAKE/usr/local/bin/pi"
rm -f "$FAKE/usr/local/bin/pi.pre-volta-root-share"
ck "absolute-path wrapper passes"  share check
ck "absolute-path wrapper survives" grep -q 'tools/image' "$FAKE/usr/local/bin/pi"
mv "$FAKE/usr/local/bin/pi" "$T/pi.saved"
if share check >"$T/check4b.log" 2>&1; then
  ck "absent pi wrapper is not drift" true
else
  ck "absent pi wrapper is not drift" false
fi
ck "absent pi wrapper is mentioned"  grep -q 'absent' "$T/check4b.log"
mv "$T/pi.saved" "$FAKE/usr/local/bin/pi"

echo "== 5. sourcing the snippet keeps the farm off PATH and heals an aliased PATH =="
sourced="$(env -i PATH="$FAKE/usr/local/lib/volta/home/bin:/usr/bin:/bin" HOME="$T/home" /bin/bash -c \
  ". '$FAKE/usr/local/lib/volta/env'; printf 'PATH=%s\nVOLTA_HOME=%s\n' \"\$PATH\" \"\$VOLTA_HOME\"")"
printf '%s\n' "$sourced" >"$T/sourced.log"
ck "farm alias pruned from PATH"   lacks grep -qF "$FAKE/usr/local/lib/volta/home/bin" "$T/sourced.log"
ck "VOLTA_HOME is the realpath"    grep -qF "VOLTA_HOME=$VHOME" "$T/sourced.log"
ck "image node precedes shims"     grep -qE "PATH=$VHOME/tools/image/node/26.12.0/bin:" "$T/sourced.log"
ck "canonical shim dir is last"    grep -qE ":$VHOME/bin\$" "$T/sourced.log"

echo "== 6. PATH without /usr/bin (the sudo su shape) still becomes usable =="
if env -i PATH="$FAKE/usr/local/lib/volta/home/bin" HOME="$T/home" /bin/bash -c \
     ". '$FAKE/usr/local/lib/volta/env'; case \":\$PATH:\" in *\":/usr/bin:\"*) exit 0 ;; *) exit 1 ;; esac"; then
  ck "/usr/bin restored for a bare PATH" true
else
  ck "/usr/bin restored for a bare PATH" false
fi

echo "== 7. alias detection has no false positives and no misses =="
ln -s "$VHOME/bin" "$T/alias-bin"
# A stale PATH in THIS shell is not installer drift: files are correct, so rc=0,
# but it is still reported (live recursion hazard until the shell re-logins).
set +e
env "${SHARE_ENV[@]}" PATH="$T/alias-bin:/usr/bin:/bin" bash "$SCRIPT" --check >"$T/check7.log" 2>&1
rc7=$?
env "${SHARE_ENV[@]}" PATH="$VHOME/bin:/usr/bin:/bin" bash "$SCRIPT" --check >"$T/check8.log" 2>&1
rc8=$?
set -e
ck "stale alias reported"        grep -q 'aliased shim dir' "$T/check7.log"
ck "stale alias is not drift"    test "$rc7" = 0
ck "canonical PATH is clean"     test "$rc8" = 0
ck "no false positive"           lacks grep -q 'aliased shim dir' "$T/check8.log"

echo
echo "passed $pass, failed $fail"
[ "$fail" = 0 ]
